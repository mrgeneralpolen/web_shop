def seed(db):
    """Заполнить пустую базу: товары, роли, права, демо-аккаунт."""
    if db.query(models.Product).count() == 0:
        for data in PRODUCTS:
            db.add(models.Product(**data))
        db.commit()

    roles = {}
    for name, description in ROLES.items():
        role = db.query(models.Role).filter_by(role_name=name).first()
        if role is None:
            role = models.Role(role_name=name, description=description)
            db.add(role)
        roles[name] = role
    db.commit()

    permissions = {}
    for name, description in PERMISSIONS.items():
        perm = db.query(models.Permission).filter_by(
            permission_code=name).first()
        if perm is None:
            perm = models.Permission(permission_code=name,
                                     description=description)
            db.add(perm)
        permissions[name] = perm
    db.commit()

    for role_name, perm_names in ROLE_PERMISSIONS.items():
        role = roles[role_name]
        have = {p.permission_code for p in role.permissions}
        for perm_name in perm_names:
            if perm_name not in have:
                role.permissions.append(permissions[perm_name])
    db.commit()

    demo = db.query(models.User).filter_by(email=DEMO_EMAIL).first()
    if demo is None:
        password_hash = hash_password(DEMO_PASSWORD)
        demo = models.User(email=DEMO_EMAIL, password_hash=password_hash,
                           full_name=DEMO_NAME, is_active=True)
        db.add(demo)
        db.commit()
        user_role = roles["user"]
        if user_role not in demo.roles:
            demo.roles.append(user_role)
        db.commit()
